class CardToolchainBuildDriverTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        scratch_override = os.environ.get("R46H_CARD_TEST_SCRATCH_ROOT")
        cls.scratch_root = (
            Path(scratch_override)
            if scratch_override
            else REPO_ROOT
            / "mainline"
            / "out"
            / ".cache"
            / "r46h-card-toolchain-driver-tests"
        )
        cls.scratch_root.mkdir(parents=True, exist_ok=True)

    @classmethod
    def tearDownClass(cls) -> None:
        try:
            cls.scratch_root.rmdir()
        except OSError:
            pass

    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory(dir=self.scratch_root)
        self.addCleanup(self.temporary.cleanup)
        self.fake_repo = Path(self.temporary.name) / "repo"
        (self.fake_repo / "mainline" / "tools" / "r46h-card-toolchain").mkdir(
            parents=True
        )
        (self.fake_repo / "mainline" / "out").mkdir(parents=True)

    def layout(self) -> object:
        return DRIVER.make_layout(
            str(self.fake_repo / "mainline" / "out" / ".cache" / "r46h-card-toolchain"),
            repo_root_override=self.fake_repo,
        )

    def directory_symlink_or_skip(self, link: Path, target: Path) -> None:
        try:
            link.symlink_to(target, target_is_directory=True)
        except (NotImplementedError, OSError) as error:
            self.skipTest(f"directory symlink fixture is unavailable: {error}")

    def initialize_source_repository(self) -> object:
        """Create a minimal, committed source closure for snapshot tests."""

        for source_name in DRIVER.BUILD_SOURCE_PATHS:
            source_path = self.fake_repo / source_name
            if source_name == "mainline/tools/r46h-card-toolchain":
                (source_path / "Cargo.toml").write_text(
                    "[workspace]\nresolver = \"2\"\n", encoding="utf-8"
                )
                (source_path / "Cargo.lock").write_text(
                    "# This file is automatically @generated by Cargo.\nversion = 4\n",
                    encoding="utf-8",
                )
            elif source_name == ".gitattributes":
                source_path.write_bytes((REPO_ROOT / source_name).read_bytes())
            else:
                source_path.parent.mkdir(parents=True, exist_ok=True)
                if source_name == "mainline/scripts/r46h_card_toolchain.py":
                    source_path.write_bytes(DRIVER_PATH.read_bytes())
                else:
                    source_path.write_text(f"fixture: {source_name}\n", encoding="utf-8")

        git_environment = os.environ.copy()
        git_environment.update(
            {
                "GIT_CONFIG_NOSYSTEM": "1",
                "GIT_CONFIG_GLOBAL": os.devnull,
                "GIT_AUTHOR_NAME": "R46H test",
                "GIT_AUTHOR_EMAIL": "r46h-test@example.invalid",
                "GIT_COMMITTER_NAME": "R46H test",
                "GIT_COMMITTER_EMAIL": "r46h-test@example.invalid",
            }
        )
        subprocess.run(
            ["git", "init", "--quiet", str(self.fake_repo)],
            check=True,
            env=git_environment,
        )
        subprocess.run(
            ["git", "-C", str(self.fake_repo), "add", "--"]
            + list(DRIVER.BUILD_SOURCE_PATHS),
            check=True,
            env=git_environment,
        )
        subprocess.run(
            [
                "git",
                "-C",
                str(self.fake_repo),
                "-c",
                "commit.gpgsign=false",
                "commit",
                "--quiet",
                "-m",
                "fixture",
            ],
            check=True,
            env=git_environment,
        )
        return self.layout()

    def publication_fixture(self) -> tuple[object, Path, Path, object]:
        layout = self.initialize_source_repository()
        DRIVER.prepare_layout(layout)
        work = layout.work_root / "publication-fixture"
        work.mkdir(mode=0o700)
        commit, tree = DRIVER.require_clean_source_scope(layout)
        source = DRIVER.capture_source_snapshot(layout, work, commit, tree)
        executable_name = "r46h-card.exe" if os.name == "nt" else "r46h-card"
        built = work / "target" / "release" / executable_name
        built.parent.mkdir(parents=True)
        built.write_bytes(b"first release binary\n")
        return layout, work, built, source

    def publish_fixture(
        self, layout: object, work: Path, built: Path, source: object
    ) -> tuple[Path, str]:
        def receipt(
            _layout: object,
            _source: object,
            executable_name: str,
            executable_sha256: str,
            executable_size: int,
            _commands: object,
            _environment: object,
            _gates: object,
            _storage_policy: str,
        ) -> dict[str, object]:
            return {
                "schema": DRIVER.BUILD_RECEIPT_SCHEMA,
                "status": "complete",
                "claim_scope": "first-party-source-and-output-integrity",
                "hermetic": False,
                "source": {
                    "cargo_lock_sha256": source.cargo_lock_sha256,
                    "driver_sha256": source.driver_sha256,
                    "file_count": source.file_count,
                    "git_commit": source.commit,
                    "git_tree": source.tree,
                    "scope": list(DRIVER.BUILD_SOURCE_PATHS),
                    "scope_clean_observed": True,
                    "snapshot_manifest_sha256": source.manifest_sha256,
                },
                "artifact": {
                    "path": executable_name,
                    "size": executable_size,
                    "sha256": executable_sha256,
                },
            }

        with mock.patch.object(DRIVER, "_publication_receipt", side_effect=receipt):
            return DRIVER.publish_release_generation(
                layout,
                work,
                built,
                source,
                {},
                {},
                [],
            )

    def refresh_generation_checksums(self, layout: object, generation: Path) -> None:
        executable_name = "r46h-card.exe" if os.name == "nt" else "r46h-card"
        names = sorted(
            {"BUILD-RECEIPT.json", "SOURCE-MANIFEST.json", executable_name},
            key=lambda item: item.encode("utf-8"),
        )
        sums = "".join(
            f"{DRIVER._sha256_file(generation / name)}  {name}\n" for name in names
        )
        (generation / "SHA256SUMS").write_text(sums, encoding="ascii")
        current_path = layout.release_dir / "CURRENT"
        current = DRIVER.json.loads(current_path.read_text(encoding="utf-8"))
        current["sha256sums_sha256"] = DRIVER._sha256_file(
            generation / "SHA256SUMS"
        )
        current_path.write_bytes(DRIVER._canonical_json(current))

