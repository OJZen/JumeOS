    def test_shared_cargo_home_prune_rejects_cross_device_root(self) -> None:
        layout = self.layout()
        DRIVER.prepare_layout(layout)
        original_stat = Path.stat

        def cross_device_stat(path: Path, *args: object, **kwargs: object) -> os.stat_result:
            metadata = original_stat(path, *args, **kwargs)
            if path == layout.cargo_home and kwargs.get("follow_symlinks") is False:
                values = list(metadata)
                values[2] = metadata.st_dev + 1
                return os.stat_result(values)
            return metadata

        with mock.patch.object(Path, "stat", cross_device_stat):
            with self.assertRaisesRegex(DRIVER.DriverError, "unsafe shared Cargo home"):
                DRIVER.prune_shared_cargo_home(layout)

