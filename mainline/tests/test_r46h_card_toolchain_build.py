class MacosNativeReadOnlySourceTests(unittest.TestCase):
    SOURCE = (
        REPO_ROOT
        / "mainline"
        / "tools"
        / "r46h-card-toolchain"
        / "crates"
        / "r46h-card-core"
        / "src"
        / "macos_native.c"
    )

    @classmethod
    def setUpClass(cls) -> None:
        cls.source = cls.SOURCE.read_text(encoding="utf-8")

    @classmethod
    def function_body(cls, name: str) -> str:
        declarations = re.finditer(
            rf"(?m)^[A-Za-z_][^;{{\n]*\b{re.escape(name)}\(", cls.source
        )
        for declaration in declarations:
            start = declaration.start()
            opening = cls.source.index("{", start)
            semicolon = cls.source.find(";", start, opening)
            if semicolon == -1:
                break
        else:
            raise AssertionError(f"missing C function: {name}")
        depth = 0
        for index in range(opening, len(cls.source)):
            if cls.source[index] == "{":
                depth += 1
            elif cls.source[index] == "}":
                depth -= 1
                if depth == 0:
                    return cls.source[opening + 1 : index]
        raise AssertionError(f"unterminated C function: {name}")

    def test_native_surface_has_no_raw_write_primitive(self) -> None:
        forbidden = (
            "O_RDWR",
            "O_WRONLY",
            "pwrite(",
            "write(",
            "fsync(",
            "DKIOCSYNCHRONIZECACHE",
        )
        for token in forbidden:
            with self.subTest(token=token):
                self.assertNotIn(token, self.source)
        self.assertIn("O_RDONLY | O_NOFOLLOW | O_CLOEXEC", self.source)
        self.assertIn("pread(", self.source)

    def test_external_path_identity_uses_the_mounted_device(self) -> None:
        resolver = self.function_body("path_whole_disk")
        self.assertIn("statfs(path, &filesystem)", resolver)
        self.assertIn("filesystem.f_mntfromname", resolver)
        self.assertIn("DADiskCreateFromBSDName", resolver)
        self.assertNotIn("DADiskCreateFromVolumePath", self.source)

    def test_partition_probe_reads_raw_and_resolves_block_identity(self) -> None:
        partition = self.function_body("r46h_macos_partition_observation")
        self.assertIn('"/dev/r%ss%u"', partition)
        self.assertIn("open(partition_raw_path, O_RDONLY", partition)
        self.assertIn("DADiskCreateFromBSDName", partition)
        self.assertIn("partition_path", partition)

    def test_claim_unmount_and_eject_state_is_preallocated_and_ordered(self) -> None:
        claim = self.function_body("r46h_macos_claim_readonly")
        self.assertLess(claim.index("DADiskClaim("), claim.index("DADiskUnmount("))
        self.assertLess(
            claim.index("session->eject_result = calloc"),
            claim.index("DADiskUnmount("),
        )
        self.assertEqual(claim.count("DADiskUnmount("), 1)
        self.assertLess(claim.index("DADiskUnmount("), claim.index("open(actual.raw_path"))

    def test_eject_deny_is_consumed_before_retry_and_drop_retries(self) -> None:
        eject = self.function_body("eject_session")
        self.assertIn(
            "wait_status != 0 && !session->eject_result->completed",
            eject,
        )
        self.assertLess(
            eject.index("if (!session->eject_result->completed)"),
            eject.index("if (session->eject_result->denied)"),
        )
        self.assertIn("session->eject_pending = 0", eject)
        self.assertIn("memset(session->eject_result, 0", eject)

        release = self.function_body("r46h_macos_session_free")
        self.assertIn("session->unmounted && !session->ejected", release)
        self.assertLess(release.index("eject_session(session)"), release.index("release_session(session)"))


