    def test_shared_cargo_home_prune_keeps_only_archives_and_index(self) -> None:
        layout = self.layout()
        DRIVER.prepare_layout(layout)
        archive = layout.cargo_home / "registry" / "cache" / "index" / "crate.crate"
        archive.parent.mkdir(parents=True)
        archive.write_bytes(b"archive")
        index = layout.cargo_home / "registry" / "index" / "index" / "config.json"
        index.parent.mkdir(parents=True)
        index.write_text("{}\n", encoding="utf-8")
        (layout.cargo_home / "registry" / "CACHEDIR.TAG").write_text(
            "Signature: 8a477f597d28d172789f06886806bc55\n",
            encoding="utf-8",
        )
        extracted = layout.cargo_home / "registry" / "src" / "index" / "crate" / "src.rs"
        extracted.parent.mkdir(parents=True)
        extracted.write_text("disposable source\n", encoding="utf-8")
        git_checkout = layout.cargo_home / "git" / "checkouts" / "crate" / "source.rs"
        git_checkout.parent.mkdir(parents=True)
        git_checkout.write_text("disposable checkout\n", encoding="utf-8")
        (layout.cargo_home / ".global-cache").write_bytes(b"state")

        DRIVER.prune_shared_cargo_home(layout)

        self.assertEqual(archive.read_bytes(), b"archive")
        self.assertEqual(index.read_text(encoding="utf-8"), "{}\n")
        self.assertTrue((layout.cargo_home / "registry" / "CACHEDIR.TAG").is_file())
        self.assertEqual(
            {entry.name for entry in layout.cargo_home.iterdir()},
            {"registry"},
        )
        self.assertEqual(
            {entry.name for entry in (layout.cargo_home / "registry").iterdir()},
            {"cache", "index", "CACHEDIR.TAG"},
        )

